// Helper functions for easy querying
export function getAllArticles(): Article[] {
  return ARTICLES;
}

export function getArticlesByCategory(categorySlug: string): Article[] {
  return ARTICLES.filter((art) => art.category === categorySlug);
}

export function getArticleBySlug(categorySlug: string, articleSlug: string): Article | undefined {
  return ARTICLES.find((art) => art.category === categorySlug && art.slug === articleSlug);
}

export function getCategoryBySlug(categorySlug: string): Category | undefined {
  return CATEGORIES.find((cat) => cat.slug === categorySlug);
}

export function getFeaturedArticles(): Article[] {
  return ARTICLES.filter((art) => art.isFeatured);
}

export function getTrendingArticles(): Article[] {
  return ARTICLES.filter((art) => art.isTrending);
}

export function searchArticles(query: string): Article[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return [];
  return ARTICLES.filter(
    (art) =>
      art.title.toLowerCase().includes(clean) ||
      art.subtitle.toLowerCase().includes(clean) ||
      art.excerpt.toLowerCase().includes(clean) ||
      art.categoryName.toLowerCase().includes(clean) ||
      art.tags.some((t) => t.toLowerCase().includes(clean)) ||
      art.topPicks.some((p) => p.name.toLowerCase().includes(clean))
  );
}
